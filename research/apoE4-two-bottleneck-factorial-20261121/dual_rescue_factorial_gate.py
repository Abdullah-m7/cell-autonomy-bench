#!/usr/bin/env python3
"""APOE3/E4 astrocyte SHIP1 x cholesterol-reduction 2x2 research QA.

PRE-EXPERIMENTAL DESIGN; no biological data generated by this code.
The source-audited tests are an early-uptake result in Gevorgyan et al.,
bioRxiv 2026 doi:10.64898/2026.05.22.726347; and lysosomal DQ-BSA
fluorescence in Mesentier-Louro et al., Cell Stem Cell 2026
 doi:10.1016/j.stem.2026.08.001. Neither tested this combination.

All numerical decision thresholds in this program are ILLUSTRATIVE and must
be prespecified with the experimental laboratory after assay calibration.
No p-values, effect claims, or clinical recommendations are produced.
"""
from __future__ import annotations
import argparse
import json
import math
from collections import Counter, defaultdict
from pathlib import Path

GENOTYPES = ('E3','E4')
SHIP1 = (0,1)
CD = (0,1)
CARGOS = ('transferrin','degradable_protein')
FATE_FIELDS = ('surface_returned_pmol','released_intact_pmol',
               'retained_intact_pmol','degraded_product_pmol','other_accounted_pmol')
NUMERIC = ('t0_internalized_pmol', 'uptake_5min_pmol', *FATE_FIELDS,
           'cell_viability_fraction','early_endosome_pH','lysosome_pH')
REQUIRED = set(NUMERIC)|{'background','batch','cell_type','genotype',
                         'ship1','cyclodextrin','cargo','degradation_chemically_verified'}

class DataQualityError(ValueError):
    pass


def nonnegative(row, key, pos=False):
    x=row[key]
    if isinstance(x,bool) or not isinstance(x,(int,float)) or not math.isfinite(x):
        raise DataQualityError(f'{key} must be a finite number')
    if x < 0 or (pos and x==0):
        raise DataQualityError(f'{key} must be '+('positive' if pos else 'nonnegative'))
    return float(x)


def contrast(arms, metric, genotype):
    y={ (ship,cd): arms[(genotype,ship,cd)][metric] for ship in SHIP1 for cd in CD }
    return {
        'vehicle':y[(0,0)],'ship1_only':y[(1,0)],
        'cyclodextrin_only':y[(0,1)],'combined':y[(1,1)],
        'ship1_delta_when_no_cd':y[(1,0)]-y[(0,0)],
        'cd_delta_when_no_ship1':y[(0,1)]-y[(0,0)],
        'interaction_difference_of_differences':y[(1,1)]-y[(1,0)]-y[(0,1)]+y[(0,0)]
    }


def summarize(payload):
    if not isinstance(payload,dict):
        raise DataQualityError('Input must be a JSON object')
    meta=payload.get('metadata',{})
    if not isinstance(meta,dict):
        raise DataQualityError('metadata must be a JSON object')
    origin=meta.get('data_origin')
    if origin not in ('SYNTHETIC_DEMO','EXPERIMENTAL'):
        raise DataQualityError('metadata.data_origin must be SYNTHETIC_DEMO or EXPERIMENTAL')
    if origin=='EXPERIMENTAL':
        if not meta.get('source_provenance') or not meta.get('assay_validation_document'):
            raise DataQualityError('EXPERIMENTAL requires source_provenance and assay_validation_document')
        if meta.get('record_unit')!='independent_differentiation_batch_summary':
            raise DataQualityError('EXPERIMENTAL requires independent_differentiation_batch_summary, not cells/images')
        if meta.get('mass_unit')!='pmol_parent_cargo_equivalents':
            raise DataQualityError('EXPERIMENTAL requires molar units in pmol_parent_cargo_equivalents, not fragment counts')
        if not meta.get('fate_pool_disjointness_document'):
            raise DataQualityError('EXPERIMENTAL requires fate_pool_disjointness_document for mass balance')
    observations=payload.get('observations')
    if not isinstance(observations,list) or not observations:
        raise DataQualityError('observations must be a nonempty array')
    blocks=defaultdict(dict)
    warnings=[]
    for ix, original in enumerate(observations):
        if not isinstance(original,dict):
            raise DataQualityError(f'row {ix} is not a record')
        missing=REQUIRED-set(original)
        if missing:
            raise DataQualityError(f'row {ix} missing fields: {sorted(missing)}')
        r=dict(original)
        for key in ('background','batch','cell_type'):
            if not isinstance(r[key],str) or not r[key].strip():
                raise DataQualityError(f'row {ix} missing nonblank {key}')
        if r['cell_type']!='isogenic_human_iPSC_astrocyte':
            raise DataQualityError(f'row {ix}: only validated isogenic human iPSC astrocytes in pilot schema')
        if r['genotype'] not in GENOTYPES or r['cargo'] not in CARGOS:
            raise DataQualityError(f'row {ix}: unsupported genotype or cargo')
        for key in ('ship1','cyclodextrin'):
            if type(r[key]) is not int or r[key] not in (0,1):
                raise DataQualityError(f'row {ix} {key} must be integer 0 or 1')
        if type(r['degradation_chemically_verified']) is not bool:
            raise DataQualityError('degradation_chemically_verified must be boolean')
        for key in NUMERIC:
            r[key]=nonnegative(r,key,pos=(key in ('t0_internalized_pmol','uptake_5min_pmol')))
        if r['t0_internalized_pmol'] < 0.01:
            raise DataQualityError(f'row {ix}: detected starting cargo too close to zero for stable fractions')
        for key in ('early_endosome_pH','lysosome_pH'):
            if not (3.5<=r[key]<=8.0):
                warnings.append(f'row {ix}: {key} outside broad assay-validity range, calibration needed')
        if r['cell_viability_fraction']>1.2:
            raise DataQualityError(f'row {ix}: viability fraction >1.2 requires redefinition')
        t0=r['t0_internalized_pmol']
        r['mass_recovered_fraction']=sum(r[f] for f in FATE_FIELDS)/t0
        r['surface_return_fraction']=r['surface_returned_pmol']/t0
        r['verified_degraded_fraction']=r['degraded_product_pmol']/t0
        r['primary_fate_fraction']=(r['surface_return_fraction'] if r['cargo']=='transferrin' else r['verified_degraded_fraction'])
        if r['cargo']=='degradable_protein' and not r['degradation_chemically_verified']:
            # Do not EVER credit unverified DQ-BSA fluorescence as proteolytic mass recovery.
            warnings.append(f'row {ix}: no chemical verification of degradation; gate fails')
        if not .90<=r['mass_recovered_fraction']<=1.10:
            warnings.append(f'row {ix}: source mass imbalance >10%; gate fails')
        block=(r['background'],r['batch'],r['cargo'])
        arm=(r['genotype'],r['ship1'],r['cyclodextrin'])
        if arm in blocks[block]:
            raise DataQualityError(f'duplicate arm {block}/{arm}; aggregate technical repeats before analysis')
        blocks[block][arm]=r
    expected={(g,s,c) for g in GENOTYPES for s in SHIP1 for c in CD}
    output=[]
    for block,arms in sorted(blocks.items()):
        missing=expected-set(arms)
        if missing:
            warnings.append(f'incomplete factorial block {block}: missing {sorted(missing)}')
            continue
        bg,batch,cargo=block
        if all(not x['degradation_chemically_verified'] for x in arms.values()) and cargo=='degradable_protein':
            warnings.append(f'{block}: no verified degraded-product assay at all')
        valid=True
        bad=[]
        for g in GENOTYPES:
            ref=arms[(g,0,0)]['t0_internalized_pmol']
            for s in SHIP1:
                for c in CD:
                    r=arms[(g,s,c)]
                    if abs(r['t0_internalized_pmol']/ref-1)>.10:
                        bad.append(f'{g} S{s} CD{c}: starting t0 cargo differs by >10% within genotype')
                    if r['mass_recovered_fraction']<.9 or r['mass_recovered_fraction']>1.1:
                        bad.append(f'{g} S{s} CD{c}: mass balance failure')
                    if r['cell_viability_fraction']<.85:
                        bad.append(f'{g} S{s} CD{c}: viability <.85')
                    if cargo=='degradable_protein' and not r['degradation_chemically_verified']:
                        bad.append(f'{g} S{s} CD{c}: degraded-product mass not chemically verified')
        valid=not bad
        z={}
        for endpoint in ('uptake_5min_pmol','primary_fate_fraction'):
            e3=contrast(arms,endpoint,'E3')
            e4=contrast(arms,endpoint,'E4')
            gap=e3['vehicle']-e4['vehicle']
            if gap <= (0.02 if endpoint=='primary_fate_fraction' else 1.0):
                recovery=None
            else:
                recovery=(e4['combined']-e4['vehicle'])/gap
            z[endpoint]={
                'E3':e3,'E4':e4,
                'genotype_difference_of_interactions':e4['interaction_difference_of_differences']-e3['interaction_difference_of_differences'],
                'baseline_E3minusE4_gap':gap,
                'combined_recovery_relative_to_baseline_genotype_gap':recovery,
                'illustrative_recovery_over_half_gap': recovery is not None and recovery>=.5
            }
        output.append({'background':bg,'batch':batch,'cargo':cargo,
                       'usable_for_pilot_comparison':valid,'quality_failures':bad,
                       'primary_fate_type':'receptor_recycling' if cargo=='transferrin' else 'chemical_proteolytic_clearance',
                       'endpoints':z})
    joint=[]
    contexts=defaultdict(dict)
    for b in output:
        contexts[(b['background'],b['batch'])][b['cargo']]=b
    for (bg,batch),pair in sorted(contexts.items()):
        both=set(pair)==set(CARGOS)
        if both:
            t=pair['transferrin'];d=pair['degradable_protein']
            # IMPORTANT: Early-uptake rescue is defined for the TRANSFERRIN route.
            # Degradable cargo can be uptake-matched without its own entry rescue:
            # requiring a second uptake rescue would bias the late fate endpoint.
            passed=(t['usable_for_pilot_comparison'] and d['usable_for_pilot_comparison']
                    and t['endpoints']['uptake_5min_pmol']['illustrative_recovery_over_half_gap']
                    and t['endpoints']['primary_fate_fraction']['illustrative_recovery_over_half_gap']
                    and d['endpoints']['primary_fate_fraction']['illustrative_recovery_over_half_gap'])
        else: passed=False
        joint.append({'background':bg,'batch':batch,'both_distinct_cargos_available':both,
                      'illustrative_combined_early_recycling_degradation_gate':passed,
                      'important': 'degradable-cargo uptake not required to improve; its measured t0 must be matched and chemical cleavage verified'})
    bgcounts=Counter(b['background'] for b in joint if b['both_distinct_cargos_available'])
    return {
      'analysis_type':'PRE_EXPERIMENTAL_FACTORIAL_DATA_QA_ONLY_NO_CAUSAL_OR_MEDICAL_CLAIM',
      'data_origin':origin,
      'source_provenance':meta.get('source_provenance','none'),
      'paper_sources':[
       'Gevorgyan et al., 2026 bioRxiv doi:10.64898/2026.05.22.726347 (human astrocyte early uptake)',
       'Mesentier-Louro et al., 2026 Cell Stem Cell doi:10.1016/j.stem.2026.08.001 (human astrocyte DQ-BSA cleavage, cholesterol correction)'],
      'shared_source_parental_backgrounds':['AG09173','KOLF2.1J'],
      'protocol':'genotype (E3/E4) x SHIP1 WT overexpression (0/1) x M-beta-cyclodextrin (0/1), 8 arms per independent parental-background/differentiation-batch/cargo',
      'illustrative_numerical_gates_not_validated':{'t0_relative_tolerance':.10,'mass_balance_min':.9,'mass_balance_max':1.1,'viability_min':.85,'recovery_of_E3minusE4_baseline_gap':.5},
      'raw_observations_received':len(observations),
      'complete_blocks':len(output),
      'block_results':output,
      'joint_two_cargo_results':joint,
      'num_unique_parental_backgrounds_with_both_cargos':len(bgcounts),
      'background_batch_counts':dict(bgcounts),
      'qa_warnings':warnings,
      'interpretive_limits':[
       'Source authors did not test this combination. Numbers in SYNTHETIC_DEMO are invented software tests, not experimental results.',
       'No p-values or population-level claims. Two parental backgrounds do not imply robust human donor-level effect size.',
       'Early transferrin uptake, surface receptor return and cleavage of a separate degradable substrate are different endpoints.',
       'A full pilot gate requires TRANSFERRIN entry and return plus degradation of the DISTINCT uptake-matched substrate, not improvement in uptake of both substrates.',
       'DQ-BSA fluorescence is secondary; chemically identified degradation product on molar units is required for this gate.',
       'Cyclodextrin can affect both membrane uptake and lysosomal state. The combined-treatment interaction is not a confirmed separation of independent routes.',
       'Matching parental genetic line NAME does not guarantee matching the exact edited clone or culture protocol across two published labs.',
       'Laboratory dose, time, biosafety, endpoint calibration and significance plan must be set before primary confirmatory experiments.',
       'No de novo ApoE4 self-aggregation inside lysosome measured; NOT a direct MecCog H3 source finding.',
      ]
    }


def synthetic_example():
    """Invented 2-parent x2-batch x2-cargo x8 arm measurements; no biology."""
    obs=[]
    for bg in ('SYNTHETIC_PARENT_A','SYNTHETIC_PARENT_B'):
        for batch in ('SYNTHETIC_BATCH_1','SYNTHETIC_BATCH_2'):
            for cargo in CARGOS:
                for g in GENOTYPES:
                    for ship in SHIP1:
                        for cd in CD:
                            if cargo=='transferrin':
                                if g=='E3':
                                    uptake=100+2*ship+2*cd
                                    fate=.70+.01*ship+.01*cd
                                else:
                                    uptake=60+30*ship+10*cd-2*ship*cd
                                    fate=.40+.04*ship+.10*cd+.09*ship*cd
                                surface=fate*100;degraded=2.
                            else:
                                if g=='E3':
                                    uptake=95+2*ship+2*cd
                                    fate=.58+.01*ship+.01*cd
                                else:
                                    uptake=65+20*ship+14*cd-1*ship*cd
                                    fate=.29+.02*ship+.15*cd+.06*ship*cd
                                surface=2.;degraded=100*fate
                            retained=100-surface-degraded-3
                            row={
                             'background':bg,'batch':batch,'cell_type':'isogenic_human_iPSC_astrocyte',
                             'genotype':g,'ship1':ship,'cyclodextrin':cd,'cargo':cargo,
                             't0_internalized_pmol':100.,'uptake_5min_pmol':uptake,
                             'surface_returned_pmol':surface,
                             'degraded_product_pmol':degraded,
                             'retained_intact_pmol':retained,'released_intact_pmol':3.,
                             'other_accounted_pmol':0.,'cell_viability_fraction':.96,
                             'early_endosome_pH':6.2,'lysosome_pH':4.7,
                             'degradation_chemically_verified':True,
                             'dq_bsa_fluorescence_secondary':'NOT_MEASURED_IN_SYNTHETIC_DEMO',
                            }
                            obs.append(row)
    return {'metadata':{'data_origin':'SYNTHETIC_DEMO',
                        'source_provenance':'INVENTED toy numbers solely for deterministic schema / factorial software QA',
                        'record_unit':'independent_differentiation_batch_summary','mass_unit':'pmol_parent_cargo_equivalents',
                        'fate_pool_disjointness_document':'SYNTHETIC example has disjoint, invented pools'},
            'observations':obs}


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--demo',action='store_true')
    p.add_argument('--input',type=Path)
    p.add_argument('--output',type=Path,required=True)
    args=p.parse_args()
    if args.demo==bool(args.input):
        p.error('Choose exactly one of --demo or --input')
    if args.output.exists():
        p.error('Refuse to overwrite existing output')
    payload=synthetic_example() if args.demo else json.loads(args.input.read_text())
    result=summarize(payload)
    args.output.write_text(json.dumps(result,indent=2,ensure_ascii=False)+'\n')
    print('DATA ORIGIN',result['data_origin'])
    print('ROWS',result['raw_observations_received'],'COMPLETE BLOCKS',result['complete_blocks'])
    print('JOINT CARGO BLOCKS',len(result['joint_two_cargo_results']))
    print('QA WARNINGS',len(result['qa_warnings']))
    print('NO BIOLOGICAL CAUSAL DISCOVERY. This tool gates a PROPOSED human-cell study only.')
    print('OUTPUT',args.output)

if __name__=='__main__':
    main()